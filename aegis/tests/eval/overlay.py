"""Policy overlay for hermetic eval / bench runs (plan 19 §2.5).

`build_policy_text(base, profile, upstream_url=None)` loads config/policy.golden.yaml (falling
back to config/policy.yaml), sets the profile, relaxes rate / loop / budget limits so they can
never trip during load (the controls stay enabled so their cost is still measured), turns the
kill switch off and optionally points the mock providers at the bench echo upstream. The result
is validated with the frozen `PolicyDoc` and only ever written to a temp dir.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "config" / "policy.golden.yaml"
POLICY = ROOT / "config" / "policy.yaml"
PROFILES = ("permissive", "balanced", "strict", "paranoid")
BIG = 10**6


def base_policy_path() -> Path:
    return GOLDEN if GOLDEN.exists() else POLICY


def build_policy_doc(base: Path | None = None, profile: str = "balanced", *,
                     upstream_url: str | None = None, slow_upstream_url: str | None = None) -> dict[str, Any]:
    src = base or base_policy_path()
    doc: dict[str, Any] = yaml.safe_load(src.read_text(encoding="utf-8")) or {}
    doc["profile"] = profile
    budgets = doc.setdefault("budgets", {})
    budgets["rate"] = {"requests_per_min": None, "tool_calls_per_min": None}
    loops = dict(budgets.get("loops") or {})
    for k in ("repeat", "error_streak", "max_steps_per_session", "cycle_k"):
        loops[k] = BIG
    budgets["loops"] = loops
    budgets["limits"] = [{
        "scope": "org:acme-capital", "window": "day", "usd": 1e9, "tokens": 1e12,
        "requests": 1e9, "compute_s": 1e9, "spend_usd": 1e9,
    }]
    budgets["kill_switch"] = {"global": False, "teams": [], "members": [], "agents": [], "sessions": []}
    # CAL: the eval agent (chaos-agent@platform) carries the demo persona purpose "Red-team test agent.";
    # strict/paranoid topic adherence then blocks every benign corpus prompt as off-purpose, which measures
    # the persona, not the guardrails. Score it against the org-wide purpose like any bank agent.
    for ctl in doc.get("controls") or []:
        if isinstance(ctl, dict) and ctl.get("id") == "INJ-03":
            purposes = ((ctl.get("params") or {}).get("adherence") or {}).get("purposes")
            if isinstance(purposes, dict):
                purposes.pop("chaos-agent@platform", None)
    if upstream_url:
        prov = doc.setdefault("providers", {})
        up = upstream_url.rstrip("/")
        if "mock-openai" in prov:
            prov["mock-openai"]["base_url"] = f"{up}/v1"
        if "mock-anthropic" in prov:
            prov["mock-anthropic"]["base_url"] = up
    if slow_upstream_url:  # bench only: "mock-slow-*" models go to a delayed echo upstream
        doc.setdefault("providers", {})["bench-slow"] = {
            "wire": "openai", "base_url": f"{slow_upstream_url.rstrip('/')}/v1", "destination": "remote"}
        models = doc.setdefault("models", {})
        models["routes"] = [{"match": "mock-slow-*", "provider": "bench-slow", "wire": "openai"},
                            *(models.get("routes") or [])]
    return doc


def validate_doc(doc: dict[str, Any]) -> None:
    """Validate with the frozen schema (raises pydantic.ValidationError)."""
    from aegis.core.policy_schema import PolicyDoc

    PolicyDoc.model_validate(doc)


def build_policy_text(base: Path | None = None, profile: str = "balanced", *,
                      upstream_url: str | None = None, slow_upstream_url: str | None = None) -> str:
    doc = build_policy_doc(base, profile, upstream_url=upstream_url, slow_upstream_url=slow_upstream_url)
    validate_doc(doc)
    header = (f"# GENERATED by tests/eval/overlay.py for a hermetic eval/bench run (profile={profile}).\n"
              "# Temp copy only; never written back to the repo.\n")
    return header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)


__all__ = ["PROFILES", "base_policy_path", "build_policy_doc", "build_policy_text", "validate_doc"]
